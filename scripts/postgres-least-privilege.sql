DO $$
BEGIN
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'urutau_migrator') THEN
    CREATE ROLE urutau_migrator LOGIN PASSWORD 'ALTERAR_EM_COFRE_SEGURO_MIGRATOR' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
  IF NOT EXISTS (SELECT FROM pg_catalog.pg_roles WHERE rolname = 'urutau_app_runtime') THEN
    CREATE ROLE urutau_app_runtime LOGIN PASSWORD 'ALTERAR_EM_COFRE_SEGURO_RUNTIME' NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION;
  END IF;
END
$$;

REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO urutau_app_runtime;
GRANT USAGE, CREATE ON SCHEMA public TO urutau_migrator;

REVOKE ALL PRIVILEGES ON ALL TABLES IN SCHEMA public FROM urutau_app_runtime;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO urutau_app_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO urutau_app_runtime;

ALTER DEFAULT PRIVILEGES FOR ROLE urutau_migrator IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO urutau_app_runtime;

ALTER DEFAULT PRIVILEGES FOR ROLE urutau_migrator IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO urutau_app_runtime;
