ALTER TABLE empresas
  ADD COLUMN IF NOT EXISTS latitude DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS longitude DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS allowed_radius_meters INTEGER NOT NULL DEFAULT 50;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'chk_empresas_allowed_radius_meters'
  ) THEN
    ALTER TABLE empresas
      ADD CONSTRAINT chk_empresas_allowed_radius_meters
      CHECK (allowed_radius_meters >= 5 AND allowed_radius_meters <= 50000);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS setores (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa_id INTEGER NOT NULL REFERENCES empresas(id) ON UPDATE CASCADE ON DELETE RESTRICT,
  nome TEXT NOT NULL,
  latitude DOUBLE PRECISION,
  longitude DOUBLE PRECISION,
  allowed_radius_meters INTEGER NOT NULL DEFAULT 50,
  atualizado_em_utc TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (allowed_radius_meters >= 5 AND allowed_radius_meters <= 50000)
);

ALTER TABLE setores
  ADD COLUMN IF NOT EXISTS latitude DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS longitude DOUBLE PRECISION,
  ADD COLUMN IF NOT EXISTS allowed_radius_meters INTEGER NOT NULL DEFAULT 50;

CREATE INDEX IF NOT EXISTS idx_setores_empresa_geofence
  ON setores (empresa_id, id);
